"""Two-stage IPD with a spline interaction, pooled jointly.

The second stage is checked against ``metafor`` 5.2.1 on a cohort generated by
:func:`cohort` below: 30 studies, 200 participants each, a logistic outcome, and
a treatment effect that is quadratic in age with study-level perturbations.  The
reference run fits one ``glm`` per study, stacks the four treatment-block
coefficients, and pools them with

    rma.mv(Y, bldiag(S), mods = ~ factor(idx) - 1,
           random = ~ factor(idx) | study, struct = "UN")

which is exactly what :func:`pimeta.ipd_two_stage_curve` does.

Tolerances: the first stage is closed form given the design, so it is compared at
1e-10; the second stage is an optimiser, compared at 1e-6.

One thing this cohort cannot show is a *non-zero* between-study covariance: with
30 studies the sampling variance of each coefficient is large enough that REML
estimates ``Sigma`` as zero, and the prediction band collapses onto the
confidence band.  The two tests that need heterogeneity build it directly
instead of hoping for it.
"""

import numpy as np
import pytest

import pimeta as ma

N_STUDY = 30
PER_STUDY = 200


def cohort(n_study: int = N_STUDY, per_study: int = PER_STUDY,
           spread: float = 1.0):
    """The deterministic cohort the R reference was generated on."""
    n = n_study * per_study
    pid = np.arange(1, n + 1)
    study = (pid - 1) // per_study + 1
    age = 40.0 + 30.0 * ((pid * 37) % 101) / 101.0
    treat = (pid % 2).astype(float)
    shift = ((study * 13) % 7 - 3) / 10.0
    h1 = ((study * 17) % 11 - 5) / 12.0 * spread
    h2 = ((study * 29) % 13 - 6) / 200.0 * spread
    h3 = ((study * 41) % 7 - 3) / 12000.0 * spread
    h4 = ((study * 53) % 7 - 3) / 90000.0 * spread
    z = age - 55.0
    eta = (-0.4 + 0.10 * treat + 0.03 * z + shift
           + treat * (0.25 + h1 + (-0.010 + h2) * z
                      + (0.0008 + h3) * z ** 2 + h4 * z ** 3))
    u = ((pid * 7919) % 1000) / 1000.0
    y = (u < 1.0 / (1.0 + np.exp(-eta))).astype(int)
    return study, age, treat, y


KNOTS = [45.0, 52.0, 60.0, 68.0]

# --- metafor: the glm of study 1 -------------------------------------------
R_THETA_1 = [0.34000715914412566, 0.003533115562011282,
             0.10361612962857279, -0.29703098750547957]
R_S_1 = [
    [0.708118629269855138, 0.0659102468971356215, -0.284128495697430650,
     0.734464429939347463],
    [0.065910246897135621, 0.0075503407783742097, -0.028743027170925105,
     0.0724862672569542704],
    [-0.284128495697430650, -0.0287430271709251048, 0.141530159849011516,
     -0.386811079893668308],
    [0.734464429939347463, 0.0724862672569542704, -0.386811079893668308,
     1.08912169277584159],
]

# --- metafor: rma.mv on the stacked block ----------------------------------
R_MU = [0.22624821498480291, -0.00057761188257125524,
        0.060482459821625534, -0.12686377867548715]
R_SE = [0.15544902297760699, 0.016077042030856213,
        0.068687616618834421, 0.18956398746818531]
R_TAU2 = [6.3415203398058981e-14, 1.4378825170424337e-14,
          3.608762803215537e-14, 4.8012443532415756e-13]

# --- metafor: the curve from B(x) and the joint covariance ------------------
R_CURVE_X = [45.0, 55.0, 65.0]
R_CURVE = {
    "est": [0.23193854986755932, 0.33402091459078326, 0.62704040955721962],
    "se": [0.070176360957960066, 0.07039370292079733, 0.073508649113829622],
    "ci_lb": [0.094395409823874871, 0.19605179212760851, 0.48296610474192148],
    "ci_ub": [0.36948168991124375, 0.47199003705395803, 0.77111471437251777],
    "pred_lb": [0.094395409811612041, 0.19605179212508031,
                0.48296610473334106],
    "pred_ub": [0.36948168992350661, 0.47199003705648623,
                0.77111471438109813],
}

# --- metafor: the two joint tests ------------------------------------------
R_INTERACTION_STAT = 21.523552829116021
R_INTERACTION_P = 8.1949427564444879e-05
R_NONLIN_STAT = 2.1246172361578397
R_NONLIN_P = 0.34565689872849709


@pytest.fixture(scope="module")
def fit():
    study, age, treat, y = cohort()
    return ma.ipd_two_stage_curve(y, study=study, treat=treat, covariate=age,
                                  knots=KNOTS)


def test_the_first_stage_is_the_study_glm(fit):
    first = fit.per_study[0]
    block = np.asarray(first.b, dtype=float)[1:5]
    assert block == pytest.approx(np.array(R_THETA_1), abs=1e-9)
    assert np.asarray(first.vb)[1:5, 1:5] == pytest.approx(
        np.array(R_S_1), abs=1e-6)
    assert np.asarray(first.vb)[1, 2] != 0.0


def test_the_joint_pooling_matches_metafor(fit):
    assert fit.coef == pytest.approx(np.array(R_MU), abs=1e-6)
    assert fit.se == pytest.approx(np.array(R_SE), abs=1e-6)
    # REML puts the between-study covariance at zero for this cohort
    assert np.allclose(np.array(fit.tau2), np.array(R_TAU2), atol=1e-9)


def test_the_curve_matches_metafor(fit):
    got = fit.curve(R_CURVE_X)
    for key, want in R_CURVE.items():
        assert np.asarray(getattr(got, key)) == pytest.approx(
            np.array(want), abs=1e-6), key


def test_the_joint_tests_match_metafor(fit):
    interaction = fit.test_interaction()
    assert interaction["stat"] == pytest.approx(R_INTERACTION_STAT, rel=1e-5)
    assert interaction["pval"] == pytest.approx(R_INTERACTION_P, rel=1e-4)
    assert interaction["df"] == 3
    nonlinear = fit.test_nonlinearity()
    assert nonlinear["stat"] == pytest.approx(R_NONLIN_STAT, rel=1e-5)
    assert nonlinear["pval"] == pytest.approx(R_NONLIN_P, rel=1e-4)
    assert nonlinear["df"] == 2


def test_the_covariance_between_coefficients_is_carried(fit):
    """Ignoring the off-diagonal would give a different standard error."""
    curve = fit.curve([55.0])
    design = fit._design(np.array([55.0]))
    diagonal_only = float(np.sqrt(float(
        ((design ** 2) @ np.diag(fit.vcov))[0])))
    assert diagonal_only != pytest.approx(float(curve.se[0]), rel=1e-3)
    # ... and the off-diagonal really is non-zero
    off = fit.vcov - np.diag(np.diag(fit.vcov))
    assert np.max(np.abs(off)) > 1e-4


def test_more_between_study_variation_widens_only_the_prediction_band():
    study, age, treat, y = cohort(n_study=12, per_study=400, spread=8.0)
    wide = ma.ipd_two_stage_curve(y, study=study, treat=treat, covariate=age,
                                  knots=KNOTS)
    assert max(wide.tau2) > 1e-3
    curve = wide.curve([55.0])
    assert curve.pred_lb[0] < curve.ci_lb[0]
    assert curve.pred_ub[0] > curve.ci_ub[0]


def test_the_curve_flags_points_outside_the_observed_range(fit):
    lo, hi = fit.support
    curve = fit.curve([lo - 5.0, 0.5 * (lo + hi), hi + 5.0])
    assert list(curve.outside) == [True, False, True]


def test_the_covariate_is_centred_at_its_median(fit):
    study, age, treat, y = cohort()
    assert fit.center == pytest.approx(float(np.median(age)), rel=1e-12)
    # the curve at the centre is the contrast vector evaluated there, by
    # construction; what centring buys is a well-identified linear coefficient
    at_median = fit.curve([fit.center])
    design = fit._design(np.array([fit.center]))
    assert at_median.est[0] == pytest.approx(
        float((design @ np.array(fit.coef))[0]), abs=1e-12)


def test_centring_can_be_switched_off():
    study, age, treat, y = cohort(n_study=6, per_study=200)
    uncentred = ma.ipd_two_stage_curve(y, study=study, treat=treat,
                                       covariate=age, knots=KNOTS, center=0.0)
    assert uncentred.center == 0.0
    # the curve itself does not depend on the parameterisation
    centred = ma.ipd_two_stage_curve(y, study=study, treat=treat,
                                     covariate=age, knots=KNOTS)
    assert centred.curve([50.0]).est[0] == pytest.approx(
        uncentred.curve([50.0]).est[0], abs=1e-6)


def test_a_balanced_study_is_not_thrown_away():
    """The old rule dropped any study with events == non-events.

    A study is only unusable when an *arm* has no variation in the outcome.
    """
    study, age, treat, y = cohort(n_study=6, per_study=200)
    # make study 1 exactly balanced without touching its arms' variation
    rows = study == 1
    arm = treat[rows] == 1.0
    n_arm = int(arm.sum())
    y2 = y.copy()
    block = y2[rows]
    block[:] = 0
    block[np.where(arm)[0][: n_arm // 2]] = 1
    block[np.where(~arm)[0][: n_arm // 2]] = 1
    y2[rows] = block
    assert int(block.sum()) * 2 == block.size
    fit = ma.ipd_two_stage_curve(y2, study=study, treat=treat, covariate=age,
                                 knots=KNOTS)
    assert "1" not in fit.excluded


def test_an_arm_without_events_is_excluded_with_the_reason():
    study, age, treat, y = cohort(n_study=6, per_study=200)
    y2 = y.copy()
    y2[(study == 2) & (treat == 1.0)] = 0
    fit = ma.ipd_two_stage_curve(y2, study=study, treat=treat, covariate=age,
                                 knots=KNOTS)
    assert "2" in fit.excluded
    assert "arm" in fit.excluded["2"]


def test_the_tables_and_the_record(fit):
    table = fit.coef_table()
    assert [row["term"] for row in table][0] == "treat"
    assert table[0]["estimate"] == pytest.approx(fit.coef[0], rel=1e-12)
    record = fit.to_dict()
    assert record["k"] == fit.k
    assert record["center"] == pytest.approx(fit.center, rel=1e-12)
    assert record["basis"]["knots"] == pytest.approx(
        np.array(KNOTS) - fit.center, rel=1e-12)


def test_diagnostics_say_when_the_covariance_is_not_identified(fit):
    diag = fit.diagnostics()
    assert diag["k"] == 30
    assert diag["n_variance_parameters"] == 10      # 4 variances + 6 correlations
    # this cohort has no detectable between-study heterogeneity
    assert diag["boundary"]
    assert diag["tau2_at_zero"] == [1, 2, 3, 4]
    assert any("prediction band necessarily equals" in n for n in diag["notes"])


def test_a_structured_covariance_is_available_for_a_small_k():
    """Six studies cannot carry an unstructured 4x4 covariance comfortably."""
    study, age, treat, y = cohort(n_study=6, per_study=200, spread=4.0)
    with pytest.warns(RuntimeWarning, match="not well identified"):
        unstructured = ma.ipd_two_stage_curve(
            y, study=study, treat=treat, covariate=age, knots=KNOTS,
            struct="UN")
    common = ma.ipd_two_stage_curve(
        y, study=study, treat=treat, covariate=age, knots=KNOTS,
        struct="HCS")
    # HCS holds one correlation for the whole block instead of six
    assert (common.diagnostics()["n_variance_parameters"]
            < unstructured.diagnostics()["n_variance_parameters"])
    assert common.k >= 4
    band = common.curve([55.0])
    assert band.ci_ub[0] > band.ci_lb[0]


def test_a_basis_with_no_curve_cannot_be_tested_for_non_linearity():
    study, age, treat, y = cohort(n_study=6, per_study=200)
    flat = ma.ipd_two_stage_curve(y, study=study, treat=treat, covariate=age,
                                  basis=ma.fp(age, [1]))
    with pytest.raises(ValueError, match="non-linear"):
        flat.test_nonlinearity()
